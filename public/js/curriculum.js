// ---- 对外接口 ----
export const CURRICULUM = CH;

export const STAGES = [
  { key: '小学', grades: ['一年级', '二年级', '三年级', '四年级', '五年级', '六年级'] },
  { key: '初中', grades: ['初一', '初二', '初三'] },
  { key: '高中', grades: ['高一', '高二', '高三'] },
];

export function subjectsOf(stage) {
  const box = CH[stage] || {};
  return Object.keys(box);
}

// 某一学段某学科的全部册（带建议年级），可按年级筛
export function booksOf(stage, subject, grade) {
  const list = ((CH[stage] || {})[subject]) || [];
  return grade ? list.filter(x => x.g === grade) : list;
}

export function unitsOf(stage, subject, book) {
  const list = ((CH[stage] || {})[subject]) || [];
  const hit = list.find(x => x.b === book);
  return hit ? hit.u.slice() : [];
}

// 全书目录纯文本，喂给模型当章节上下文
export function outlineOf(stage, subject) {
  const list = ((CH[stage] || {})[subject]) || [];
  return list.map(x => `${x.b}：${x.u.join('、')}`).join('\n');
}

// ---- 反查：给一段题面/错题文字，猜最像的章节 ----
export function stageOfGrade(grade) {
  const g = String(grade || '');
  for (const st of STAGES) if (st.grades.includes(g)) return st.key;
  if (/^[一二三四五六]年级/.test(g)) return '小学';
  if (/^[初七]/.test(g)) return '初中';
  if (/^高/.test(g)) return '高中';
  return '';
}

function bigrams(s) {
  const t = String(s || '').replace(/[^\u4e00-\u9fa5A-Za-z0-9]+/g, '');
  const out = new Set();
  for (let i = 0; i < t.length - 1; i++) out.add(t.slice(i, i + 2));
  return out;
}

function overlapScore(text, unit) {
  const a = bigrams(text);
  const b = bigrams(unit);
  if (!a.size || !b.size) return 0;
  let hit = 0;
  for (const g of b) if (a.has(g)) hit += 1;
  let score = hit / b.size;
  if (String(text).includes(unit)) score += 0.6;
  return score;
}

// 返回 { stage, subject, grade, book, chapter, score }，找不到返回 null
export function guessChapter(text, opts = {}) {
  const src = String(text || '');
  if (!src.trim()) return null;
  const stageHint = opts.stage || '';
  const subjectHint = opts.subject || '';
  const gradeHint = opts.grade || '';
  let best = null;
  for (const st of STAGES) {
    if (stageHint && st.key !== stageHint) continue;
    for (const sub of subjectsOf(st.key)) {
      if (subjectHint && sub !== subjectHint) continue;
      for (const bk of booksOf(st.key, sub)) {
        const gradeBonus = gradeHint && bk.g === gradeHint ? 0.12 : 0;
        for (const u of bk.u) {
          const sc = overlapScore(src, u) + gradeBonus;
          if (sc > 0.15 && (!best || sc > best.score)) {
            best = { stage: st.key, subject: sub, grade: bk.g, book: bk.b, chapter: u, score: sc };
          }
        }
      }
    }
  }
  return best;
}
